import { chromium } from '@playwright/test'
import { readdir, readFile, mkdir, writeFile } from 'node:fs/promises'
import assert from 'node:assert/strict'
const jsFiles = (await readdir('dist/assets')).filter(f => f.endsWith('.js'))
const js = (await Promise.all(jsFiles.map(f=>readFile(`dist/assets/${f}`, 'utf8')))).join('\n')
for (const marker of ['Studio preview', 'Clock held', 'URLSearchParams', 'readPreview']) assert.ok(!js.includes(marker), `Development code leaked: ${marker}`)
assert.equal(jsFiles.some(f => /PreviewDock|preview-/.test(f)), false)
const output = 'work/screenshots'
await mkdir(output, {recursive:true})
const browser = await chromium.launch({executablePath:process.env.CHROMIUM_PATH || '/usr/bin/chromium',headless:true,args:['--no-sandbox']})
const errors=[]
try {
  const page = await browser.newPage({viewport:{width:390,height:844},reducedMotion:'reduce'})
  page.on('pageerror',e=>errors.push(e.message))
  page.on('response',r=>{if(r.status()>=400) errors.push(`${r.status()} ${r.url()}`)})
  await page.clock.install({time:new Date('2026-11-11T17:18:06Z')})
  await page.goto('http://localhost:4173/?scene=bouquet&at=2099-01-01T00:00:00Z&clean=0')
  await page.locator('[data-scene="countdown"]').waitFor()
  assert.equal(await page.getByRole('navigation',{name:'Development scene preview'}).count(),0)
  await page.evaluate(()=>document.fonts.ready)
  await page.waitForFunction(()=>[...document.images].every(i=>i.complete && i.naturalWidth>0))
  await page.screenshot({path:`${output}/production-countdown-390x844.png`})
  await page.clock.setFixedTime(new Date('2026-11-11T21:12:00Z'))
  await page.goto('http://localhost:4173/?scene=countdown&at=2000-01-01T00:00:00Z')
  await page.locator('[data-scene="opening"]').waitFor()
  await page.evaluate(()=>document.fonts.ready)
  await page.waitForFunction(()=>[...document.images].every(i=>i.complete && i.naturalWidth>0))
  await page.screenshot({path:`${output}/production-opening-390x844.png`})
  await page.getByRole('button',{name:'Enter my little universe'}).click()
  await page.locator('[data-scene="garden"]').waitFor()
  await page.waitForFunction(()=>[...document.images].every(i=>i.complete && i.naturalWidth>0))
  await page.screenshot({path:`${output}/production-garden-390x844.png`})
  await page.getByRole('button',{name:'Grow your flowers'}).click()
  await page.locator('[data-scene="grow"]').waitFor()
  await page.getByRole('button',{name:"Let's make something beautiful"}).click()
  await page.getByRole('button',{name:/Plant a flower in the garden/}).press('Enter')
  assert.equal(await page.locator('[data-flower]').count(),1)
  await page.getByRole('button',{name:/Select grown/}).click()
  await page.getByRole('button',{name:'Add to bouquet',exact:true}).click()
  await page.getByRole('button',{name:'My bouquet · 1'}).click()
  await page.getByRole('button',{name:'Wrap My Bouquet'}).click()
  await page.getByRole('button',{name:'Save My Bouquet'}).waitFor()
  await page.waitForFunction(()=>!document.querySelector('.save-bouquet')?.disabled)
  assert.equal(await page.locator('[data-bouquet-flower]').count(),1)
  assert.deepEqual(errors,[])
  await writeFile(`${output}/production-verification.json`,JSON.stringify({passed:true,checks:['No dev preview JavaScript in production bundle','No preview navigation in production DOM','Malicious scene and future-date query ignored before release','Past-date and countdown query ignored after release','Normal opening-to-garden flow works','No browser or network errors'],errors},null,2))
  console.log('PASS: Production preview stripping, query protection, release states and normal navigation. Three clean production captures saved.')
} finally {await browser.close()}
